// 基本算术运算测试
int main() {
    int a = 10, b = 5;
    int sum = a + b;
    int diff = a - b;
    int product = a * b;
    int quotient = a / b;

    printf("a = %d, b = %d\n", a, b);
    printf("Sum: %d\n", sum);
    printf("Difference: %d\n", diff);
    printf("Product: %d\n", product);
    printf("Quotient: %d\n", quotient);

    return 0;
}
